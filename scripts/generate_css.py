"""Build the shipped stylesheet from the design-system tokens and the source stylesheets.

Usage:
    python scripts/generate_css.py          # write src/michel_albert_sphinx/static/michel-albert.css
    python scripts/generate_css.py --check  # exit 1 if the shipped file is out of date

Inputs:
    src/michel_albert_sphinx/tokens.json  the design system's tokens (copy of project/tokens.json)
    styles/base.css                       content rules shared by every theme
    styles/immaterial.css                 sphinx-immaterial adapter
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PKG = ROOT / "src" / "michel_albert_sphinx"
OUT = PKG / "static" / "michel-albert.css"

# Selectors under which sphinx-immaterial renders its dark ("slate") scheme.
DARK_SELECTOR = "[data-md-color-scheme=slate], :root:has(> body[data-md-color-scheme=slate])"

LATIN = (
    "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,"
    "U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD"
)
LATIN_EXT = (
    "U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,"
    "U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C4,U+2113,U+2C60-2C7F,U+A720-A7FF"
)
FONTS = [  # (family, file prefix, weight, style)
    ("Source Sans 3", "source-sans-3", 400, "normal"),
    ("Source Sans 3", "source-sans-3", 400, "italic"),
    ("Source Sans 3", "source-sans-3", 600, "normal"),
    ("Source Sans 3", "source-sans-3", 600, "italic"),
    ("Source Code Pro", "source-code-pro", 400, "normal"),
    ("Source Code Pro", "source-code-pro", 600, "normal"),
]


def font_faces() -> str:
    out = []
    for family, prefix, weight, style in FONTS:
        for subset, ranges in (("latin", LATIN), ("latin-ext", LATIN_EXT)):
            out.append(
                f'@font-face {{ font-family: "{family}"; font-style: {style}; font-weight: {weight}; '
                f'font-display: swap; src: url("fonts/{prefix}-{subset}-{weight}-{style}.woff2") format("woff2"); '
                f"unicode-range: {ranges}; }}"
            )
    return "\n".join(out)


def token_blocks(tokens: dict) -> str:
    colors = tokens["color"]["tokens"]
    themes = [t["id"] for t in tokens["color"]["themes"]]
    if not {"light", "dark"} <= set(themes):
        raise SystemExit("tokens.json must define 'light' and 'dark' colour themes")

    def value(tok: dict, theme: str) -> str:
        v = tok["value"]
        if isinstance(v, str):
            return v
        return v.get(theme, v[themes[0]])

    families = tokens["type"]["families"]
    radii = {t["name"]: t["value"] for t in tokens["radius"]["tokens"]}
    light = "\n".join(f"  --ma-{t['name']}: {value(t, 'light')};" for t in colors)
    dark = "\n".join(f"  --ma-{t['name']}: {value(t, 'dark')};" for t in colors)
    return (
        ":root {\n  color-scheme: light;\n"
        f"{light}\n"
        f"  --ma-sans: {families['sans']};\n"
        f"  --ma-mono: {families['mono']};\n"
        f"  --ma-radius-sm: {radii['radius-sm']}; --ma-radius-md: {radii['radius-md']};\n"
        "}\n\n"
        f"{DARK_SELECTOR} {{\n  color-scheme: dark;\n{dark}\n}}"
    )


def build() -> str:
    tokens = json.loads((PKG / "tokens.json").read_text(encoding="utf-8"))
    parts = [
        f"/* {tokens['name']} design system for Sphinx (sphinx-immaterial).",
        "   GENERATED by scripts/generate_css.py from tokens.json and styles/*.css. Do not edit by hand. */",
        "",
        font_faces(),
        "",
        token_blocks(tokens),
        "",
        (ROOT / "styles" / "base.css").read_text(encoding="utf-8").strip(),
        "",
        (ROOT / "styles" / "immaterial.css").read_text(encoding="utf-8").strip(),
        "",
    ]
    return "\n".join(parts)


def main() -> int:
    css = build()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != css:
            print(f"{OUT.relative_to(ROOT)} is out of date; run: python scripts/generate_css.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(css, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(css):,} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
